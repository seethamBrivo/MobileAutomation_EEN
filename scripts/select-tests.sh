#!/usr/bin/env bash
# Picks the test classes a pull request affects and writes a TestNG suite for them.
#
#   scripts/select-tests.sh <base-branch> <android|ios> [output-suite.xml]
#
# Prints the selected classes (one per line) and writes the suite file (default testng-pr.xml).
# For tests, set CHANGED_FILES to a newline-separated list instead of using git diff.
#
# Rules:
#   - a changed or new test class under src/test/java/tests is selected;
#   - a changed page or locator class selects every test class that uses it, directly or through other
#     pages/locators (so a locator change reaches the tests of every page that uses it);
#   - a change to shared framework code (base, utils, listeners, constants, reports, resources, pom,
#     testng*.xml, workflows) cannot be traced to single tests, so the SMOKE classes run;
#   - docs and other files select nothing;
#   - on iOS only classes with methods in the "ios" group are kept, and the suite filters on that group.
set -euo pipefail

BASE="${1:?base branch}"
PLATFORM="${2:-android}"
OUT="${3:-testng-pr.xml}"

SMOKE="tests.ts_login.LoginTest tests.ts_dashboard.ResellerDashboardTest"
# Own <test> after the pool: one attach ID on one account, so never next to another end-user class.
ALONE="tests.ts_bridges.BridgesTest"
# Not device tests.
EXCLUDE="tests.ts_diagnostics.HierarchyDumpTest"

if [ -n "${CHANGED_FILES:-}" ]; then
  changed="$CHANGED_FILES"
else
  changed="$(git diff --name-only --diff-filter=d "origin/${BASE}...HEAD")"
fi

declare -A selected=()
select_class() { selected["$1"]=1; }

fqcn_of() { # src/test/java/tests/ts_x/FooTest.java -> tests.ts_x.FooTest
  local f="${1#src/test/java/}"; f="${f%.java}"; echo "${f//\//.}"
}

names=()  # simple class names changed in pages/ or locators/
infra=0
while IFS= read -r f; do
  [ -z "$f" ] && continue
  case "$f" in
    src/test/java/tests/*.java) select_class "$(fqcn_of "$f")" ;;
    src/main/java/pages/*.java|src/main/java/locators/*.java) n="${f##*/}"; names+=("${n%.java}") ;;
    src/main/java/*|src/main/resources/*|src/test/java/base/*|src/test/java/utils/*|src/test/java/listeners/*|pom.xml|browserstack.yml|testng*.xml|.github/*|scripts/*) infra=1 ;;
  esac
done <<< "$changed"

# Follow the references: a class that mentions a changed page/locator is affected too.
if [ "${#names[@]}" -gt 0 ]; then
  declare -A seen=()
  queue=("${names[@]}")
  while [ "${#queue[@]}" -gt 0 ]; do
    n="${queue[0]}"; queue=("${queue[@]:1}")
    [ -n "${seen[$n]:-}" ] && continue
    seen[$n]=1
    while IFS= read -r user; do
      [ -z "$user" ] && continue
      case "$user" in
        src/test/java/tests/*) select_class "$(fqcn_of "$user")" ;;
        *) b="${user##*/}"; queue+=("${b%.java}") ;;
      esac
    done < <(grep -rlw --include='*.java' -- "$n" src/main/java/pages src/main/java/locators src/test/java/tests 2>/dev/null || true)
  done
fi

if [ "$infra" -eq 1 ]; then
  for c in $SMOKE; do select_class "$c"; done
fi

for c in $EXCLUDE; do unset "selected[$c]"; done

if [ "$PLATFORM" = "ios" ]; then
  for c in "${!selected[@]}"; do
    f="src/test/java/${c//./\/}.java"
    grep -q '"ios"' "$f" 2>/dev/null || unset "selected[$c]"
  done
fi

pool=(); alone=()
for c in $(printf '%s\n' "${!selected[@]}" | sort); do
  if [[ " $ALONE " == *" $c "* ]]; then alone+=("$c"); else pool+=("$c"); fi
done

groups_xml=""
if [ "$PLATFORM" = "ios" ]; then
  groups_xml='<groups><run><include name="ios"/></run></groups>'
fi

{
  echo '<!DOCTYPE suite SYSTEM "https://testng.org/testng-1.0.dtd">'
  echo '<!-- Generated by scripts/select-tests.sh for a pull request. Do not commit. -->'
  echo '<suite name="PR affected tests" parallel="classes" thread-count="2">'
  echo '  <listeners>'
  echo '    <listener class-name="listeners.TestListener"/>'
  echo '    <listener class-name="listeners.RetryTransformer"/>'
  echo '    <listener class-name="io.qameta.allure.testng.AllureTestNg"/>'
  echo '  </listeners>'
  if [ "${#pool[@]}" -gt 0 ]; then
    echo '  <test name="Affected classes">'
    echo "    $groups_xml"
    echo '    <classes>'
    for c in "${pool[@]}"; do echo "      <class name=\"$c\"/>"; done
    echo '    </classes>'
    echo '  </test>'
  fi
  if [ "${#alone[@]}" -gt 0 ]; then
    echo '  <test name="Affected classes (run alone)" parallel="false" thread-count="1">'
    echo "    $groups_xml"
    echo '    <classes>'
    for c in "${alone[@]}"; do echo "      <class name=\"$c\"/>"; done
    echo '    </classes>'
    echo '  </test>'
  fi
  echo '</suite>'
} > "$OUT"

printf '%s\n' "${pool[@]}" "${alone[@]}" | sed '/^$/d'
